export function filterSpots(
  spots: Spot[],
  query: string,
  filter: SpotFilter
): Spot[] {
  const normalized = query.trim().toLowerCase();
  return spots.filter((spot) => {
    if (filter === 'saved' && spot.savedSizeMb === null) return false;
    if (filter === 'favorite' && !spot.isFavorite) return false;
    if (!normalized) return true;
    const haystack = [
      spot.name,
      spot.subtitle,
      spot.province,
      spot.region,
      `${spot.lat}, ${spot.lng}`,
      ...spot.tags,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(normalized);
  });
}
